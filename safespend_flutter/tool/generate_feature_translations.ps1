param(
  [string]$ManifestPath = 'tool/translation_manifest.json',
  [string]$OutputPath = 'lib/l10n/translations_features.dart'
)

$ErrorActionPreference = 'Stop'

function New-BingSession {
  $session = New-Object Microsoft.PowerShell.Commands.WebRequestSession
  $page = (Invoke-WebRequest `
      -UseBasicParsing `
      -Uri 'https://www.bing.com/translator?setlang=en' `
      -WebSession $session `
      -TimeoutSec 30).Content

  $ig = [regex]::Match($page, 'IG:"([^"]+)"').Groups[1].Value
  $iid = [regex]::Match($page, 'data-iid="([^"]+)"').Groups[1].Value
  $abuse = [regex]::Match(
    $page,
    'params_AbusePreventionHelper\s*=\s*\[([0-9]+),"([^"]+)",([0-9]+)\]'
  )
  if (-not $ig -or -not $iid -or -not $abuse.Success) {
    throw 'Could not read the Bing translation session metadata.'
  }

  return @{
    Session = $session
    Ig = $ig
    Iid = $iid
    Key = $abuse.Groups[1].Value
    Token = $abuse.Groups[2].Value
    RequestNumber = 1
  }
}

function Protect-Placeholders([string]$Value) {
  return [regex]::Replace($Value, '\{(\w+)\}', '__SSPH_$1__')
}

function Restore-Placeholders([string]$Value) {
  return [regex]::Replace($Value, '__SSPH_(\w+)__', '{$1}')
}

function Invoke-BingTranslation(
  [hashtable]$Bing,
  [string]$Text,
  [string]$TargetLanguage
) {
  $url = "https://www.bing.com/ttranslatev3?isVertical=1&IG=$($Bing.Ig)&IID=$($Bing.Iid).$($Bing.RequestNumber)"
  $Bing.RequestNumber = [int]$Bing.RequestNumber + 1
  $body = @{
    fromLang = 'en'
    text = $Text
    to = $TargetLanguage
    token = $Bing.Token
    key = $Bing.Key
    tryFetchingGenderDebiasedTranslations = 'true'
  }
  $response = Invoke-RestMethod `
    -Uri $url `
    -Method Post `
    -Body $body `
    -WebSession $Bing.Session `
    -ContentType 'application/x-www-form-urlencoded' `
    -TimeoutSec 30
  $payload = if ($response -is [array]) { $response[0] } else { $response }
  if ($null -eq $payload.translations -or $payload.translations.Count -eq 0) {
    throw "Bing returned no translation: $($response | ConvertTo-Json -Depth 8 -Compress)"
  }
  return [string]$payload.translations[0].text
}

function Convert-Map(
  [hashtable]$Bing,
  [object[]]$Properties,
  [string]$TargetLanguage
) {
  $translated = [ordered]@{}
  $start = 0

  while ($start -lt $Properties.Count) {
    $end = $start
    $length = 0
    while ($end -lt $Properties.Count) {
      $protected = Protect-Placeholders ([string]$Properties[$end].Value)
      $nextLength = $length + $protected.Length + 24
      if ($end -gt $start -and $nextLength -gt 900) { break }
      $length = $nextLength
      $end++
    }

    $chunk = @($Properties[$start..($end - 1)])
    $parts = for ($index = 0; $index -lt $chunk.Count; $index++) {
      $marker = $index.ToString('0000')
      "[[SS_$marker]]`n$(Protect-Placeholders ([string]$chunk[$index].Value))"
    }
    $result = Invoke-BingTranslation $Bing ($parts -join "`n") $TargetLanguage
    $matches = [regex]::Matches(
      $result,
      '\[\[SS_(\d{4})\]\]\s*([\s\S]*?)(?=\s*\[\[SS_|$)'
    )
    if ($matches.Count -ne $chunk.Count) {
      Write-Warning "Batch markers changed for $TargetLanguage; retrying $($chunk.Count) strings individually."
      foreach ($property in $chunk) {
        $value = Invoke-BingTranslation `
          $Bing `
          (Protect-Placeholders ([string]$property.Value)) `
          $TargetLanguage
        $translated[$property.Name] = Restore-Placeholders $value.Trim()
      }
      $start = $end
      continue
    }

    foreach ($match in $matches) {
      $index = [int]$match.Groups[1].Value
      $value = Restore-Placeholders $match.Groups[2].Value.Trim()
      $translated[$chunk[$index].Name] = $value
    }
    $start = $end
  }

  return $translated
}

function ConvertTo-DartString([string]$Value) {
  return ConvertTo-Json -Compress -InputObject $Value
}

$languageCodes = [ordered]@{
  fr = 'fr'
  ar = 'ar'
  es = 'es'
  de = 'de'
  pt = 'pt'
  it = 'it'
  tr = 'tr'
  nl = 'nl'
  ru = 'ru'
  zh = 'zh-Hans'
  ja = 'ja'
  ko = 'ko'
  hi = 'hi'
  id = 'id'
  pl = 'pl'
}

$manifest = Get-Content -LiteralPath $ManifestPath -Raw -Encoding UTF8 |
  ConvertFrom-Json
$generated = [ordered]@{}
$generated.en = [ordered]@{}
foreach ($property in ($manifest.en.PSObject.Properties | Sort-Object Name)) {
  $generated.en[$property.Name] = [string]$property.Value
}

$bing = New-BingSession
foreach ($locale in $languageCodes.Keys) {
  $properties = @($manifest.$locale.PSObject.Properties | Sort-Object Name)
  Write-Output "Translating $($properties.Count) strings to $locale..."
  $generated[$locale] = Convert-Map $bing $properties $languageCodes[$locale]
}

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add('// Generated by tool/generate_feature_translations.ps1.')
$lines.Add('// Existing human-edited strings are never overwritten.')
$lines.Add('const translationsFeatures = <String, Map<String, String>>{')
foreach ($locale in @('en') + @($languageCodes.Keys)) {
  $lines.Add("  $(ConvertTo-DartString $locale): {")
  foreach ($entry in $generated[$locale].GetEnumerator()) {
    $key = ConvertTo-DartString ([string]$entry.Key)
    $value = ConvertTo-DartString ([string]$entry.Value)
    $lines.Add("    $key`: $value,")
  }
  $lines.Add('  },')
}
$lines.Add('};')

$resolvedOutput = [System.IO.Path]::GetFullPath((Join-Path (Get-Location) $OutputPath))
[System.IO.File]::WriteAllLines(
  $resolvedOutput,
  $lines,
  [System.Text.UTF8Encoding]::new($false)
)
Write-Output "Wrote $resolvedOutput"
